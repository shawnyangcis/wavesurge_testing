import { expect, test } from '@playwright/test';
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
test('实际浏览器复现待人工阻塞独立搜索，并验证自然语言取消后恢复与停止', async ({page}) => {
  test.setTimeout(300000);
  const root='.gstack/qa-reports/full-e2e-2026-10-10';
  const docker=(...args:string[])=>execFileSync('docker',['compose',...args],{encoding:'utf8'});
  const password=docker('exec','-T','app','cat','/app/data/admin-bootstrap.txt').trim();
  await page.goto('/'); await page.getByLabel('管理员密码').fill(password); await page.getByRole('button',{name:/进入工作室/}).click(); await expect(page.getByLabel('研究对话')).toBeVisible();
  const get=async(path:string)=>(await page.request.get(path)).json();
  const state=async()=>get('/api/state');
  const send=async(text:string)=>{await page.getByRole('textbox',{name:'发送消息'}).fill(text);await page.getByRole('button',{name:'发送消息'}).click();await expect.poll(async()=>(await state()).active,{timeout:120000}).toBe(false);};
  await expect.poll(async()=>(await state()).active,{timeout:120000}).toBe(false);
  docker('cp','tests/fixtures/seed-browser-task.ts','app:/app/data/fixtures/seed-browser-task.ts');
  const nonce=`block-${Date.now()}`;
  const aId=docker('exec','-T','app','node','data/fixtures/seed-browser-task.ts',nonce,'http://127.0.0.1:8085/skip');
  const a=async()=>(await state()).tasks.find((t:any)=>t.id===aId);
  await expect.poll(async()=>(await a())?.status,{timeout:180000,intervals:[2000]}).toBe('needs_input');
  const bTitle=`Review独立文字队列 ${nonce}`;
  const beforeIds=(await state()).tasks.map((t:any)=>t.id);
  await send(`现在请另外启动一项独立免费研究，标题“${bTitle}”。找1位 Instagram 的科技内容创作者，创作者所在地 United States，粉丝1万至10万，最多1个候选；分享科技内容是必选文字条件，没有视觉条件，不要求邮箱。立即开始这项研究，不要改变或取消任何已有任务，也不做外联。`);
  await expect.poll(async()=>(await state()).tasks.filter((t:any)=>!beforeIds.includes(t.id)).length).toBe(1);
  const bId=(await state()).tasks.find((t:any)=>!beforeIds.includes(t.id)).id;
  const b=async()=>(await state()).tasks.find((t:any)=>t.id===bId);
  await page.waitForTimeout(16000);
  const blocked={a:await a(),b:await b(),desktop:await get('/api/desktop'),waveCalls:(await get('/api/debug')).waveCalls.filter((c:any)=>c.request?.requestId===bId)};
  expect(blocked.b.status).toBe('queued');expect(blocked.b.remoteId).toBeUndefined();expect(blocked.waveCalls).toHaveLength(0);
  writeFileSync(root+'/concurrency-cancel.json',JSON.stringify({source:'controlled blocked candidate A + actual browser, model and free WaveSurge B',blocked},null,2));
  await page.screenshot({path:root+'/screenshots/independent-search-blocked.png',fullPage:true});
  await send(`请取消任务“${(await a()).title}”（编号 ${aId}），我不处理这次人工协助。保持独立任务“${bTitle}”继续执行，不要重新提交或另建任何研究。`);
  await expect.poll(async()=>(await a()).status).toBe('cancelled');
  await expect.poll(async()=>(await b()).remoteId,{timeout:60000}).toBeTruthy();
  expect((await get('/api/desktop')).request).toBeUndefined();
  const recovered={a:await a(),b:await b(),waveCalls:(await get('/api/debug')).waveCalls.filter((c:any)=>c.request?.requestId===bId)};
  expect(recovered.waveCalls.filter((c:any)=>c.method==='POST')).toHaveLength(1);
  writeFileSync(root+'/concurrency-cancel.json',JSON.stringify({source:'controlled blocked candidate A + actual browser, model and free WaveSurge B',blocked,recovered},null,2));
  await send(`请停止“${bTitle}”（编号 ${bId}）的本地研究，不要另建研究。`);
  await expect.poll(async()=>(await b()).status).toBe('cancelled');
  await page.locator('.task').filter({has:page.getByRole('heading',{name:bTitle,exact:true})}).getByRole('button',{name:'查看结果'}).click();
  await expect(page.getByRole('dialog',{name:'研究结果'})).toBeVisible();await expect(page.getByText('暂时没有已保存的核验结果。')).toBeVisible();
  const popupPromise=page.waitForEvent('popup');await page.getByRole('link',{name:'查看报告',exact:true}).click();const popup=await popupPromise;await expect(popup.getByText(/已停止本地核验/)).toBeVisible();await popup.screenshot({path:root+'/screenshots/cancelled-report.png',fullPage:true});await popup.close();
  const cancelled={a:await a(),b:await b(),desktop:await get('/api/desktop')};
  writeFileSync(root+'/concurrency-cancel.json',JSON.stringify({source:'A is an explicit controlled blocked-browser candidate; B is started and cancelled through natural-language UI with actual model and real free WaveSurge API; passed defect reproduction does NOT mean independent scheduling works',blocked,recovered,cancelled},null,2));
});
