import { expect, test } from '@playwright/test';
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
test.use({ trace: 'off' });
test('Campaign弹窗在后台完成后自动同步分组数量', async ({ page }) => {
  test.setTimeout(140000);
  const root = '.gstack/qa-reports/full-e2e-2026-10-10';
  const docker = (...args: string[]) => execFileSync('docker', ['compose', '-p', 'creator-studio-review-e2e', '-f', 'compose.yaml', '-f', root + '/compose.override.yaml', ...args], { encoding: 'utf8' });
  const password = docker('exec', '-T', 'app', 'cat', '/app/data/admin-bootstrap.txt').trim();
  await page.goto('/'); await page.getByLabel('管理员密码').fill(password); await page.getByRole('button', { name: /进入工作室/ }).click(); await expect(page.getByLabel('研究对话')).toBeVisible();
  docker('cp', root + '/seed-stale-plan.ts', 'app:/app/data/fixtures/seed-stale-plan.ts');
  const seed = JSON.parse(docker('exec', '-T', 'app', 'node', 'data/fixtures/seed-stale-plan.ts', String(Date.now())));
  const get = async () => (await page.request.get('/api/campaigns/' + seed.id)).json();
  const before = await get(); expect(before.matched).toBe(0);
  await page.getByRole('button', { name: 'Campaign 方案', exact: true }).click(); const dialog = page.getByRole('dialog', { name: 'Campaign 方案' });
  const card = dialog.locator('article.task').filter({ has: page.getByRole('heading', { name: seed.title + ' · v1', exact: true }) });
  await card.getByRole('button', { name: '查看方案与配额' }).click();
  const detail = dialog.locator('.campaign-detail'); await expect(detail.getByRole('heading', { name: before.groups[0].spec.title + ' · 0/1', exact: true })).toBeVisible();
  await dialog.screenshot({ path: root + '/screenshots/campaign-refresh-before.png' });
  await expect.poll(async () => (await get()).status, { timeout: 100000 }).toBe('completed');
  await expect(card).toContainText('去重入选 2/2', { timeout: 10000 });
  const after = await get();
  await expect(detail.getByRole('heading', { name: before.groups[0].spec.title + ' · 1/1', exact: true })).toBeVisible();
  const refreshedDetail = await detail.innerText();
  await dialog.screenshot({ path: root + '/screenshots/campaign-refresh-automatic.png' });
  await card.getByRole('button', { name: '查看方案与配额' }).click();
  await expect(detail.getByRole('heading', { name: before.groups[0].spec.title + ' · 1/1', exact: true })).toBeVisible();
  const reopenedDetail = await detail.innerText(); await dialog.screenshot({ path: root + '/screenshots/campaign-refresh-reopened.png' });
  writeFileSync(root + '/campaign-refresh.json', JSON.stringify({ seed, before, after, refreshedDetail, reopenedDetail, result: 'automatic selected-detail and campaign-card refresh confirmed, completed 2/2', limitation: 'controlled basic-condition candidates, not actual social profiles or LLM semantic filtering' }, null, 2));
});
