import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { randomBytes, randomUUID } from 'node:crypto';
import { Store } from './store.ts';
import { initializeAdmin } from './auth.ts';
import { createApp } from './app.ts';
import { SettingsManager } from './settings.ts';
import { Context } from './context.ts';
import { ModelClient } from './model.ts';
import { Agent } from './agent.ts';
import { basicTools } from './tools.ts';
import { registerDebug } from './debug-api.ts';
import { WaveClient } from './wave.ts';
import { repairStoredResults, repairStoredTags, repairAnnotationDrift, repairFollowerPrecision, repairFactorReferences } from './repair.ts';
import { ResearchEngine } from './research.ts';
import { modelVerifier } from './verify.ts';
import { researchTools } from './research-tools.ts';
import { registerResearch } from './research-api.ts';
import { DesktopBroker, desktopToken } from './desktop.ts';
import { registerDesktop } from './desktop-api.ts';
import { browserVerifier } from './browser-verifier.ts';
import { CampaignService } from './campaign.ts';
import { candidateSelector } from './shortlist.ts';
import { campaignTools } from './campaign-tools.ts';
import { registerCampaigns } from './campaign-api.ts';
import { recoverWorkBatches } from './work-delivery.ts';
export async function start(env: NodeJS.ProcessEnv) {
  const dataDir = resolve(env.DATA_DIR ?? 'data');
  mkdirSync(dataDir, { recursive: true, mode: 0o700 });
  const store = new Store(resolve(dataDir, 'studio.sqlite'));
  const password = env.ADMIN_PASSWORD ?? randomBytes(18).toString('base64url');
  if (initializeAdmin(store, password)) writeFileSync(resolve(dataDir, 'admin-bootstrap.txt'), password, { mode: 0o600 });
  const settings = new SettingsManager(store, env);
  const context = new Context(store, randomUUID);
  const model = new ModelClient(store, settings, fetch, Date.now, randomUUID);
  const wave = new WaveClient(env.WAVESURGE_TOKEN ?? '', store, fetch, Date.now, randomUUID, env.WAVESURGE_BASE_URL);
  const desktop = env.DESKTOP_URL ? new DesktopBroker(store, env.DESKTOP_URL, desktopToken(env.DESKTOP_TOKEN_FILE ?? resolve(dataDir, 'desktop-token')), resolve(dataDir, 'assets'), fetch, Date.now) : undefined;
  const engine = new ResearchEngine(store, wave, desktop ? browserVerifier(model, settings, desktop, store) : modelVerifier(model, settings), Date.now);
  engine.textVerify = modelVerifier(model, settings);
  engine.shortlist = candidateSelector(model, settings);
  repairStoredResults(engine);
  repairAnnotationDrift(engine);
  repairStoredTags(engine);
  repairFollowerPrecision(engine);
  repairFactorReferences(engine);
  engine.enrichment.annotate = modelVerifier(model, settings);
  const campaigns = new CampaignService(store, engine, Date.now);
  engine.onProgress = () => campaigns.deliver();
  recoverWorkBatches(store, Date.now());
  const agent = new Agent(store, settings, context, model, campaignTools(campaigns, researchTools(engine, basicTools(store), desktop)), Date.now, randomUUID);
  const app = createApp({ store, now: Date.now, publicDir: resolve('dist'), onMessage: () => { void agent.wake(); }, active: () => agent.active });
  registerDebug(app, store, settings, agent);
  registerResearch(app, engine, desktop ? id => desktop.image(id) : undefined);
  registerCampaigns(app, campaigns, desktop ? id => desktop.image(id) : undefined);
  if (desktop) registerDesktop(app, desktop, () => { void engine.wake(); });
  const leaseTimer = setInterval(() => { if (desktop) void desktop.expire().then(expired => { if (expired) void engine.wake(); }).catch(() => {}); }, 1000);
  const timer = setInterval(() => { void engine.wake(); }, 1000);
  app.addHook('onClose', async () => { clearInterval(timer); clearInterval(leaseTimer); agent.stopped = true; engine.stopped = true; await agent.currentRun; await engine.currentRun; store.close(); });
  await app.listen({ port: Number(env.PORT ?? 3000), host: '0.0.0.0' });
  void agent.wake();
  void engine.wake();
  return app;
}
